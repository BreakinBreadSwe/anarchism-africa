-- HOUSE LAB — saved projects (sketch → plan → budget → pitch), one row per
-- project, owned by the signed-in email. Apply once in the Supabase SQL
-- editor or:
--   psql "$SUPABASE_DB_URL" < db/migrations/2026-09-house-projects.sql

CREATE TABLE IF NOT EXISTS house_projects (
  id           text PRIMARY KEY,                 -- hp_<12 hex>, generated by the API
  owner_email  text NOT NULL,
  name         text NOT NULL DEFAULT 'Untitled house',
  plan         jsonb NOT NULL,                   -- normalized plan (rooms, roof, features, totals)
  options      jsonb NOT NULL DEFAULT '{}',      -- { city, quality, sweat_equity, owner_equity, land_cost, applicant, site, story }
  pitch        text,                             -- markdown
  thumbnail    text,                             -- data URL snapshot of the 3D view
  updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS house_projects_owner_idx   ON house_projects(owner_email);
CREATE INDEX IF NOT EXISTS house_projects_updated_idx ON house_projects(updated_at DESC);
